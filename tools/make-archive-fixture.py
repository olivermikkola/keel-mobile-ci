#!/usr/bin/env python3
"""Builds HarnessTests/ArchiveFixture.swift: a small real git archive and its tree listing.

  python3 tools/make-archive-fixture.py HarnessTests/ArchiveFixture.swift

Commit hashes change on every run (the commit time is not fixed); the tests
read them from the generated file.
"""
import base64, gzip, os, subprocess, sys, tempfile, zlib
out = sys.argv[1]
d = tempfile.mkdtemp()
def w(path, data):
    full = os.path.join(d.encode(), path if isinstance(path, bytes) else path.encode())
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "wb").write(data if isinstance(data, bytes) else data.encode())
def git(*a, **k): return subprocess.run(["git", "-C", d, "-c", "core.quotepath=off", *a], check=True, capture_output=True, **k).stdout
git("init", "-q", "-b", "main"); git("config", "user.name", "t"); git("config", "user.email", "t@t.invalid")
git("config", "core.precomposeunicode", "false")
w("README.md", "# Fixture\n\nA tiny repository for workspace tests.\nThe prefix cache keeps prompt tokens.\n")
w("Sources/App.swift", "import Foundation\n\npublic struct AppConfig {\n    let name: String\n}\n\nfinal class DownloadManager {\n    func resumeDownload() {}\n    private var prefixCache: [Int] = []\n}\n\nfunc makeConfig() -> AppConfig { AppConfig(name: \"x\") }\n")
w("Sources/util/helpers.py", "class Parser:\n    def parse(self, text):\n        return text.split()\n\ndef load_table(path):\n    return open(path).read()\n")
w("Sources/Makefile", "all:\n\techo upper\n")
w("Sources/makefile", "all:\n\techo lower\n")
w("docs/café.txt", "composed\n")
w("docs/café.txt", "decomposed\n")
w("docs/empty.txt", "")
w("assets/logo.bin", bytes(range(256)) * 4)
w("assets/crlf.txt", "one\r\ntwo\r\n")
long_dir = "deep/" + "/".join(["segment-with-a-long-name-%02d" % i for i in range(6)])
w(long_dir + "/final-file-with-a-long-name.txt", "long path content\n")
lines = "".join("let value%d = compute(%d) // repeated filler line for back references\n" % (i, i * 7) for i in range(400))
w("Sources/Generated.swift", lines)
os.symlink("README.md", os.path.join(d, "link"))
git("add", "-A"); git("commit", "-q", "-m", "fixture")
commit = git("rev-parse", "HEAD").decode().strip(); tree = git("rev-parse", "HEAD^{tree}").decode().strip()
rows = []
for row in git("ls-tree", "-r", "-l", "-z", "HEAD").split(b"\0"):
    if not row: continue
    meta, path = row.split(b"\t", 1); mode, typ, sha, size = meta.split()
    rows.append((path, mode.decode(), typ.decode(), sha.decode(), size.decode()))
tar = git("archive", "--prefix=fixture-%s/" % commit[:7], "HEAD")
def swift_bytes(b): return "String(decoding: [" + ", ".join(str(x) for x in b) + "] as [UInt8], as: UTF8.self)"
def lit(path):
    try:
        s = path.decode()
        if all(32 <= ord(c) < 127 for c in s): return '"%s"' % s
    except Exception: pass
    return swift_bytes(path)
variants = {
    "dynamic": gzip.compress(tar, 9, mtime=0),
}
c = zlib.compressobj(9, zlib.DEFLATED, 31, 9, zlib.Z_FIXED); variants["fixed"] = c.compress(tar) + c.flush()
with open(out, "w") as f:
    f.write("// Generated by a script from a real `git archive`; do not edit by hand.\n")
    f.write("// The same tarball in three DEFLATE encodings, plus `git ls-tree -r -l` of its commit.\n")
    f.write("import Foundation\n\nenum ArchiveFixture {\n")
    f.write('    static let commit = "%s"\n    static let tree = "%s"\n' % (commit, tree))
    f.write("    static let entries: [(path: String, mode: String, type: String, sha: String, size: Int?)] = [\n")
    for path, mode, typ, sha, size in rows:
        f.write('        (%s, "%s", "%s", "%s", %s),\n' % (lit(path), mode, typ, sha, "nil" if size == "-" else size))
    f.write("    ]\n")
    for name, data in variants.items():
        b = base64.b64encode(data).decode()
        f.write("    static let %s = Data(base64Encoded: \"\"\"\n" % name)
        for i in range(0, len(b), 120): f.write("        " + b[i:i+120] + "\n")
        f.write('        """, options: .ignoreUnknownCharacters)!\n')
    f.write("}\n")
print(commit, len(tar), {k: len(v) for k, v in variants.items()})
